
const mongoose = require("mongoose");

const pendingRegistrationSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true
  },
  email: {
    type: String,
    required: true,
    unique: true,
    lowercase: true
  },
  password: {
    type: String,
    required: true
  },
  otpHash: {
    type: String,
    required: true
  },
  attempts: {
    type: Number,
    default: 0
  },
  expiresAt: {
    type: Date,
    required: true,
    expires: 0
  }
});

module.exports = mongoose.model(
  "PendingRegistration",
  pendingRegistrationSchema
);
